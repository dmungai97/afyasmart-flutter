#!/usr/bin/env node
// Regenerates supabase/seed.sql from the seed-data/*.json catalogue files,
// which are also read directly by the map screen for its unauthenticated,
// non-paywalled list.
//
//   node scripts/build-supabase-seed.js

const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const read = (name) =>
  JSON.parse(fs.readFileSync(path.join(root, "seed-data", name), "utf8"));

const lit = (value) => {
  if (value === undefined || value === null) return "null";
  if (typeof value === "number") return String(value);
  if (typeof value === "boolean") return value ? "true" : "false";
  return `'${String(value).replace(/'/g, "''")}'`;
};

// Column order per table; each record is projected through this so a missing
// key in the JSON becomes an explicit null rather than a shifted column.
const tables = [
  {
    table: "doctors",
    file: "doctors.json",
    columns: [
      "name", "specialization", "hospital", "location", "region", "phone",
      "email", "latitude", "longitude", "experience_years", "rating",
      "availability", "available",
    ],
  },
  {
    table: "drugs",
    file: "drugs.json",
    columns: [
      "name", "generic_name", "category", "uses", "dosage", "side_effects",
      "pregnancy_safe", "alcohol_safe", "lactation_safe", "prescription_required",
    ],
  },
  {
    table: "pharmacies",
    file: "pharmacies.json",
    columns: [
      "name", "location", "address", "phone", "email", "latitude", "longitude",
      "opening_hours", "open_24hrs", "open",
    ],
  },
];

const out = [
  "-- Generated by scripts/build-supabase-seed.js — do not edit by hand.",
  "-- Source: seed-data/*.json",
  "",
  "-- Idempotent: truncate lets the seed be re-run against a dev database",
  "-- without stacking duplicate rows. RESTART IDENTITY keeps ids stable",
  "-- across reseeds, which matters because the client treats them as",
  "-- meaningful numbers.",
  "truncate public.doctors, public.drugs, public.pharmacies restart identity cascade;",
  "",
];

for (const { table, file, columns } of tables) {
  const rows = read(file);
  out.push(`-- ${table}: ${rows.length} rows`);
  out.push(`insert into public.${table} (${columns.join(", ")}) values`);
  out.push(
    rows
      .map((row) => `  (${columns.map((c) => lit(row[c])).join(", ")})`)
      .join(",\n") + ";",
  );
  out.push("");
}

const target = path.join(root, "supabase", "seed.sql");
fs.writeFileSync(target, out.join("\n"), "utf8");
console.log(
  `Wrote ${path.relative(root, target)} — ` +
    tables.map(({ table, file }) => `${read(file).length} ${table}`).join(", "),
);
